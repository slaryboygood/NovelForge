"""M2A：Story Planning IR V1（Design / Models / Schema / Validator / Versioning）。

Story Planning IR = future planning truth：写小说之前到底要规划什么。
它位于 NOVEL_SPEC 之下、Chapter Semantic IR 之上：

    NOVEL_SPEC → Story Planning IR → StorySpine → Route Lab → VolumePlan → ArcPlan
    → Chapter Semantic IR → Detailed Outline

边界（与 Canon / StoryState / Chapter IR 不互相替代）：

- Canon = confirmed stable truth；StoryState = happened runtime truth；
  Chapter Semantic IR = 章节执行计划；Planning IR 只引用它们的稳定 ID。
- Planning 不能把 future 写成 happened；Chapter IR 不能偷偷改 Planning truth；
  promotion / confirmation / state application 必须经过正式 service。

M2A 不实现 Builder / Compiler / LLM Planner（M2B / M3）。
"""

